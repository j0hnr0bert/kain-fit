// Stage 3A golden evaluation corpus (Part 2/3/4/5).
//
// 120 unique meal-logging utterances: 40 English, 40 Filipino/Tagalog, 40
// Taglish. Of each language's 40, 20 are adversarial (10 minimal pairs)
// and 20 are broad-coverage (foods, dishes, quantities, units,
// modifiers, speech behavior). 30 adversarial pairs total (Part 4),
// spread 10 per language, each realizing one of the 15 required
// contrasts in exactly 2 of the 3 languages.
//
// normalizedReferenceTranscript is computed from intendedTranscript via
// the real normalizeTranscript() — never hand-duplicated — so the
// reference can never silently drift out of sync with the actual
// normalization rules.
//
// Ground-truth honesty (Part 6): every field defaults to null/empty and
// is only filled in when the speaker actually said it. Nothing here
// infers unspoken dish ingredients, invents a quantity for an unquantified
// food, or resolves a spoken range to a single fabricated number — see
// the "range" and "mixed dish" entries below for how that's handled
// explicitly (quantity: null, with reviewerNotes explaining why).

import { normalizeTranscript } from "../scoring/normalize";
import type {
  CorpusRecord,
  ExpectedFoodEntity,
  SemanticMealSignature,
  LanguageGroup,
  DifficultyLevel,
  ChallengeCategory,
  TestSplit,
} from "./types";

function food(
  f: Partial<ExpectedFoodEntity> & Pick<ExpectedFoodEntity, "food" | "spokenAs">,
): ExpectedFoodEntity {
  return {
    quantity: null,
    unit: null,
    preparation: [],
    stateModifiers: [],
    packedMedium: null,
    brand: null,
    ...f,
  };
}

function sig(
  partial: Partial<SemanticMealSignature> &
    Pick<SemanticMealSignature, "foods" | "utteranceLanguage">,
): SemanticMealSignature {
  return {
    additions: [],
    exclusions: [],
    negations: [],
    corrections: [],
    codeSwitchPoints: [],
    criticalTokens: [],
    ...partial,
  };
}

function rec(input: {
  id: string;
  languageGroup: LanguageGroup;
  intendedTranscript: string;
  expected: SemanticMealSignature;
  difficulty: DifficultyLevel;
  challengeCategories: ChallengeCategory[];
  testSplit: TestSplit;
  isAdversarial: boolean;
  adversarialPairId?: string | null;
  reviewerNotes?: string;
  speakingRate?: "normal" | "fast" | "quiet" | null;
  noiseCondition?: "quiet" | "normal_room" | "gym" | "fan_ac" | null;
}): CorpusRecord {
  return {
    id: input.id,
    languageGroup: input.languageGroup,
    intendedTranscript: input.intendedTranscript,
    normalizedReferenceTranscript: normalizeTranscript(input.intendedTranscript),
    expected: input.expected,
    difficulty: input.difficulty,
    challengeCategories: input.challengeCategories,
    testSplit: input.testSplit,
    isAdversarial: input.isAdversarial,
    adversarialPairId: input.adversarialPairId ?? null,
    reviewerNotes: input.reviewerNotes ?? "",
    audioFixtureId: null,
    speakerId: null,
    deviceMetadata: null,
    browserMetadata: null,
    microphoneMetadata: null,
    noiseCondition: input.noiseCondition ?? null,
    speakingRate: input.speakingRate ?? null,
  };
}

